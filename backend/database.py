import json
import uuid
import os

from datetime import datetime
from pathlib import Path

import psycopg
from psycopg.rows import dict_row
from dotenv import load_dotenv


# Load environment variables from backend/.env
BASE_DIR = Path(__file__).resolve().parent
load_dotenv(BASE_DIR / ".env")

DATABASE_URL = os.getenv("DATABASE_URL")

if not DATABASE_URL:
    raise ValueError("DATABASE_URL is missing from backend/.env")


def get_connection():
    """Create and return a PostgreSQL database connection."""

    return psycopg.connect(
        DATABASE_URL,
        row_factory=dict_row,
        sslmode="require"
    )


def init_db():
    """Create the applications table if it does not exist."""

    with get_connection() as connection:
        connection.execute("""
            CREATE TABLE IF NOT EXISTS applications (
                id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                application_id TEXT UNIQUE NOT NULL,
                company_name TEXT NOT NULL,
                decision TEXT NOT NULL,
                reason TEXT,
                checks TEXT,
                follow_up TEXT,
                vendor_data TEXT,
                submitted_at TEXT NOT NULL
            )
        """)


def save_application(vendor, result):
    """Save a vendor application and its verification result."""

    application_id = (
        "VF-"
        + datetime.now().strftime("%Y%m%d")
        + "-"
        + uuid.uuid4().hex[:6].upper()
    )

    submitted_at = datetime.now().isoformat(timespec="seconds")

    # Mask the bank account number before storing vendor information.
    safe_vendor_data = vendor.copy()

    account_number = safe_vendor_data.get("bank_account_number", "")

    if account_number:
        safe_vendor_data["bank_account_number"] = (
            "********" + str(account_number)[-4:]
        )

    with get_connection() as connection:
        connection.execute("""
            INSERT INTO applications (
                application_id,
                company_name,
                decision,
                reason,
                checks,
                follow_up,
                vendor_data,
                submitted_at
            )
            VALUES (%s, %s, %s, %s, %s, %s, %s, %s)
        """, (
            application_id,
            vendor.get("company_name", "Unknown"),
            result.get("decision", "PENDING"),
            result.get("reason", ""),
            json.dumps(result.get("checks", [])),
            json.dumps(result.get("follow_up", [])),
            json.dumps(safe_vendor_data),
            submitted_at
        ))

    return application_id


def get_all_applications():
    """Retrieve all applications, newest first."""

    with get_connection() as connection:
        rows = connection.execute("""
            SELECT *
            FROM applications
            ORDER BY id DESC
        """).fetchall()

    applications = []

    for row in rows:
        application = dict(row)

        application["checks"] = json.loads(
            application["checks"] or "[]"
        )

        application["follow_up"] = json.loads(
            application["follow_up"] or "[]"
        )

        application["vendor_data"] = json.loads(
            application["vendor_data"] or "{}"
        )

        applications.append(application)

    return applications


def get_application(application_id):
    """Retrieve one application using its unique ID."""

    with get_connection() as connection:
        row = connection.execute("""
            SELECT *
            FROM applications
            WHERE application_id = %s
        """, (application_id,)).fetchone()

    if row is None:
        return None

    application = dict(row)

    application["checks"] = json.loads(
        application["checks"] or "[]"
    )

    application["follow_up"] = json.loads(
        application["follow_up"] or "[]"
    )

    application["vendor_data"] = json.loads(
        application["vendor_data"] or "{}"
    )

    return application